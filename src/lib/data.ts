export function getEmployeeById(id: string | null): Employee | undefined {
  if (!id) return undefined;
  return EMPLOYEES.find((e) => e.id === id);
}

export function getMachineById(id: string): Machine | undefined {
  return MACHINES.find((m) => m.id === id);
}

export function getMachinesByOperator(operatorId: string): Machine[] {
  return MACHINES.filter((m) => m.operatorId === operatorId);
}

export function getTechnicianName(id: string): string {
  return getEmployeeById(id)?.name ?? "Không rõ";
}
